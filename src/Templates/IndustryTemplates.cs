    public static string GetTemplate(IndustryType industry)
    {
        return industry switch
        {
            IndustryType.Development => DevelopmentTemplate,
            IndustryType.Design => DesignTemplate,
            IndustryType.Marketing => MarketingTemplate,
            IndustryType.SEO => SeoTemplate,
            _ => GeneralTemplate
        };
    }

    public static string GetPricingGuidelines(IndustryType industry)
    {
        return industry switch
        {
            IndustryType.Development => DevelopmentPricing,
            IndustryType.Design => DesignPricing,
            IndustryType.Marketing => MarketingPricing,
            IndustryType.SEO => SeoPricing,
            _ => GeneralPricing
        };
    }

